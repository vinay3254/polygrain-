// scripts/deploy.js — Deploy MeetingRegistry to Polygon and save ABI to frontend
const { ethers } = require("hardhat");
const fs   = require("fs");
const path = require("path");

async function main() {
  // ── 1. Print deployer info ────────────────────────────────────────────────
  const [deployer] = await ethers.getSigners();
  const balance    = await ethers.provider.getBalance(deployer.address);

  console.log("──────────────────────────────────────────");
  console.log("  Deploying MeetingRegistry");
  console.log("──────────────────────────────────────────");
  console.log(`  Deployer : ${deployer.address}`);
  console.log(`  Balance  : ${ethers.formatEther(balance)} MATIC`);

  // ── 2. Deploy contract ────────────────────────────────────────────────────
  console.log("\n  Deploying...");
  const Factory  = await ethers.getContractFactory("MeetingRegistry");
  const registry = await Factory.deploy();
  await registry.waitForDeployment();

  const contractAddress = await registry.getAddress();
  console.log(`  ✔ Deployed to: ${contractAddress}`);

  // ── 3. Load ABI from Hardhat artifacts ───────────────────────────────────
  // The artifact is generated by `npx hardhat compile` into artifacts/
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/MeetingRegistry.sol/MeetingRegistry.json"
  );
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

  // ── 4. Save address + ABI to frontend/src/contracts/ ─────────────────────
  // The React hook imports this JSON directly — no env var needed at runtime.
  // This file is overwritten on every deploy; commit it after deploying.
  const outputDir  = path.join(__dirname, "../frontend/src/contracts");
  const outputPath = path.join(outputDir, "MeetingRegistry.json");

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(
    outputPath,
    JSON.stringify({ address: contractAddress, abi: artifact.abi }, null, 2)
  );
  console.log(`  ✔ ABI + address saved to ${outputPath}`);

  // ── 5. Print next steps ───────────────────────────────────────────────────
  console.log("\n──────────────────────────────────────────");
  console.log("  Next steps:");
  console.log(`  1. Add to .env:         CONTRACT_ADDRESS=${contractAddress}`);
  console.log(`  2. Add to frontend/.env: VITE_CONTRACT_ADDRESS=${contractAddress}`);
  console.log(`  3. Verify on Polygonscan:`);
  console.log(`     npx hardhat verify --network mumbai ${contractAddress}`);
  console.log("──────────────────────────────────────────\n");
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
